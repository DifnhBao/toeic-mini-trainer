import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { after, before, describe, it } from "node:test";
import type { PrismaClient } from "@prisma/client";
import { SignJWT } from "jose";

// Never fall back to DATABASE_URL, .env or a cloud DB. The name and loopback
// host are intentionally fixed so destructive fixture cleanup cannot reach
// an existing project database.
const testUrl = process.env.TEST_DATABASE_URL;
if (!testUrl || process.env.ALLOW_INTEGRATION_TEST_DATABASE !== "true") {
  throw new Error("Integration tests require explicit TEST_DATABASE_URL and ALLOW_INTEGRATION_TEST_DATABASE=true");
}
const parsed = new URL(testUrl);
if (!["localhost", "127.0.0.1", "[::1]"].includes(parsed.hostname) || parsed.pathname !== "/toeic_release_test" || process.env.NODE_ENV === "production") {
  throw new Error("Integration tests only accept the isolated local toeic_release_test database");
}
process.env.DATABASE_URL = testUrl;
process.env.MOBILE_JWT_SECRET = "integration-only-mobile-secret-never-deployed";
process.env.RATE_LIMIT_STORE = "database";

let prisma: PrismaClient;
let submit: typeof import("../../app/api/mini-tests/[id]/submit/route");
let getTest: typeof import("../../app/api/v1/tests/[id]/route");
let auth: typeof import("../../app/lib/mobile-auth");
let rateLimit: typeof import("../../app/lib/rate-limit");
let usage: typeof import("../../app/lib/ai-usage");
let learning: typeof import("../../app/lib/learning-data");
let generate: typeof import("../../app/api/mini-tests/generate/route");
const userA = randomUUID(); const userB = randomUUID();
const questionA = randomUUID(); const questionB = randomUUID();
const testId = randomUUID();
const deviceId = "integration-test-device";
const context = { params: Promise.resolve({ id: testId }) };
const ownUsageKeys = new Set<string>();
const ownUserIds: string[] = [userA, userB];

before(async () => {
  prisma = (await import("../../app/lib/prisma")).prisma;
  submit = await import("../../app/api/mini-tests/[id]/submit/route");
  getTest = await import("../../app/api/v1/tests/[id]/route");
  auth = await import("../../app/lib/mobile-auth");
  rateLimit = await import("../../app/lib/rate-limit");
  usage = await import("../../app/lib/ai-usage");
  learning = await import("../../app/lib/learning-data");
  generate = await import("../../app/api/mini-tests/generate/route");
  await prisma.user.createMany({ data: [
    { id: userA, email: `${userA}@test.invalid` }, { id: userB, email: `${userB}@test.invalid` },
  ] });
  await prisma.question.createMany({ data: [
    { id: questionA, ownerId: userA, part: 5, content: "A", options: { A: "yes", B: "no" }, correctAnswer: "A" },
    { id: questionB, ownerId: userA, part: 2, content: "B", options: { A: "one", B: "two", C: "three" }, correctAnswer: "C" },
  ] });
  await prisma.miniTest.create({ data: { id: testId, title: "Integration fixture", createdById: userA, questions: { create: [
    { questionId: questionA, orderIndex: 1 }, { questionId: questionB, orderIndex: 2 },
  ] } } });
});

after(async () => {
  if (!prisma) return;
  // Only UUIDs generated by this run are deleted. No truncate/reset/seed.
  await prisma.miniTest.deleteMany({ where: { OR: [{ id: testId }, { createdById: { in: ownUserIds } }] } });
  await prisma.user.deleteMany({ where: { id: { in: ownUserIds } } });
  await prisma.userAiUsage.deleteMany({ where: { key: { in: [...ownUsageKeys] } } });
  await prisma.$disconnect();
});

async function request(userId: string, body?: unknown, headers?: Record<string, string>) {
  const token = await new SignJWT({ tokenUse: "access" }).setProtectedHeader({ alg: "HS256" })
    .setSubject(userId).setIssuer("toeic-mini-trainer").setAudience("toeic-mobile").setExpirationTime("5m")
    .sign(new TextEncoder().encode(process.env.MOBILE_JWT_SECRET));
  return new Request("https://integration.invalid/test", {
    method: body === undefined ? "GET" : "POST",
    headers: { authorization: `Bearer ${token}`, "content-type": "application/json", ...headers },
    ...(body === undefined ? {} : { body: JSON.stringify(body) }),
  });
}

describe("PostgreSQL release acceptance", () => {
  it("keeps answers private before submit and excludes another account", async () => {
    const response = await getTest.GET(await request(userA), context);
    assert.equal(response.status, 200);
    const payload = await response.json();
    assert.equal(payload.test.ownerId, userA);
    const text = JSON.stringify(payload);
    assert.ok(!text.includes("correctAnswer"));
    assert.equal((await getTest.GET(await request(userB), context)).status, 404);
  });

  it("persists exactly one correctly scored attempt under concurrent retries", async () => {
    const clientSubmissionId = randomUUID();
    const body = { clientSubmissionId, durationSeconds: 45, answers: { [questionA]: "A" } };
    const results = await Promise.all(Array.from({ length: 5 }, async () => {
      const response = await submit.POST(await request(userA, body), context);
      assert.equal(response.status, 200); return response.json();
    }));
    assert.equal(new Set(results.map((result) => result.attemptId)).size, 1);
    assert.ok(results.every((result) => result.score === 1));
    assert.equal(await prisma.testAttempt.count({ where: { clientSubmissionId } }), 1);
    const rows = await prisma.userAnswer.findMany({ where: { attemptId: results[0].attemptId } });
    assert.equal(rows.length, 2);
    assert.equal(rows.filter((answer) => answer.isCorrect).length, 1);
    assert.equal(rows.find((answer) => answer.questionId === questionB)?.selectedOption, null);
    assert.equal((await submit.POST(await request(userB, body), context)).status, 409);
  });

  it("rejects forged IDs and unavailable choices without storing attempts", async () => {
    const beforeCount = await prisma.testAttempt.count({ where: { testId } });
    for (const answers of [{ [randomUUID()]: "A" }, { [questionB]: "D" }]) {
      assert.equal((await submit.POST(await request(userA, {
        clientSubmissionId: randomUUID(), durationSeconds: 1, answers,
      }), context)).status, 400);
    }
    assert.equal(await prisma.testAttempt.count({ where: { testId } }), beforeCount);
  });

  it("rotates refresh tokens once and revokes the family on token reuse", async () => {
    const initial = await auth.createMobileSession(userA, deviceId);
    const replacement = await auth.rotateRefreshToken(initial.refreshToken, deviceId);
    assert.ok(replacement);
    assert.equal(await auth.rotateRefreshToken(initial.refreshToken, deviceId), null);
    assert.equal(await auth.rotateRefreshToken(replacement.refreshToken, deviceId), null);
    const session = await prisma.mobileSession.findFirst({ where: { userId: userA } });
    assert.ok(session && session.tokenHash !== initial.refreshToken);
  });

  it("logout revokes refresh and suspended users cannot access a test", async () => {
    const session = await auth.createMobileSession(userA, deviceId);
    await auth.revokeRefreshToken(session.refreshToken);
    assert.equal(await auth.rotateRefreshToken(session.refreshToken, deviceId), null);
    await prisma.user.update({ where: { id: userB }, data: { status: "SUSPENDED" } });
    assert.equal((await getTest.GET(await request(userB), context)).status, 401);
    await prisma.user.update({ where: { id: userB }, data: { status: "ACTIVE" } });
  });

  it("enforces a shared allowance regardless of forged client IP headers", async () => {
    const scope = `integration:${randomUUID()}`;
    const existing = new Set((await prisma.userAiUsage.findMany({ select: { key: true } })).map((row) => row.key));
    const responses = await Promise.all(Array.from({ length: 12 }, (_, index) =>
      rateLimit.takeRateLimit(new Request("https://integration.invalid", { headers: { "x-real-ip": `198.51.100.${index + 1}` } }), scope, 3, 60_000)));
    assert.equal(responses.filter((result) => result.allowed).length, 3);
    const added = await prisma.userAiUsage.findMany({ where: { key: { startsWith: "rate:" } }, select: { key: true } });
    added.filter((row) => !existing.has(row.key)).forEach((row) => ownUsageKeys.add(row.key));
  });

  it("stops all provider calls when the emergency switch is off", async () => {
    process.env.AI_ENABLED = "false";
    try { assert.equal(await usage.consumeDailyAiCall(userA, "coach", 20), false); }
    finally { delete process.env.AI_ENABLED; }
  });

  it("uses the same bounded selection and validates web generation", async () => {
    assert.equal((await generate.POST(await request(userA, { limit: 100, part: "mixed" }))).status, 400);
    assert.equal((await generate.POST(await request(userA, { limit: 5, part: "invalid" }))).status, 400);
    const response = await generate.POST(await request(userA, { limit: 5, part: "5" }));
    assert.equal(response.status, 201);
    const body = await response.json();
    const test = await prisma.miniTest.findUnique({ where: { id: body.testId }, include: { questions: true } });
    assert.equal(test?.createdById, userA);
    assert.deepEqual(test?.questions.map((item) => item.questionId), [questionA]);
    assert.deepEqual(await learning.selectPracticeQuestions(userB, [5], 50), []);
  });

  it("aggregates progress in SQL without mixing users", async () => {
    const summary = await learning.learningSummary(userA);
    assert.equal(summary.totalAnswered, 2);
    assert.equal(summary.overallAccuracy, 50);
    assert.deepEqual(summary.partStats, [{ part: 2, total: 1, accuracy: 0 }, { part: 5, total: 1, accuracy: 100 }]);
    assert.equal((await learning.learningSummary(userB)).totalAnswered, 0);
  });

  it("does not auto-link a new provider by a matching verified email", async () => {
    await assert.rejects(auth.resolveMobileUser({
      provider: "apple", providerAccountId: randomUUID(), email: `${userA}@test.invalid`, emailVerified: true,
    }), auth.AccountLinkRequiredError);
    assert.equal(await prisma.account.count({ where: { userId: userA } }), 0);
  });

  it("keeps a provider subject stable when its displayed email changes", async () => {
    const subject = randomUUID();
    const identity = { provider: "google" as const, providerAccountId: subject, email: `${subject}@test.invalid`, emailVerified: true };
    const created = await auth.resolveMobileUser(identity); ownUserIds.push(created.id);
    const again = await auth.resolveMobileUser({ ...identity, email: `${randomUUID()}@test.invalid` });
    assert.equal(again.id, created.id);
    assert.equal(await prisma.account.count({ where: { provider: "google", providerAccountId: subject } }), 1);
  });
});
